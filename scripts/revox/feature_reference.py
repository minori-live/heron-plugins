"""Regenerate the compact Revox mel fixture using the model's PyTorch frontend.

Run with target/revox/venv/bin/python after installing requirements.lock.
The Rust fixture is kept in crates/revox-dsp/src/features.rs. This script prints
reference values only; it does not rewrite expected values in a failing test.
FCPE feature evidence is generated by export_fcpe.py using upstream source.
"""

import json

import librosa
import numpy as np
import torch


count = 4097
time = np.arange(count, dtype=np.float64) / 48000.0
audio = (0.3 * np.sin(2 * np.pi * 220 * time)
         + 0.1 * np.cos(2 * np.pi * 660 * time)).astype(np.float32)
spectrum = torch.stft(
    torch.from_numpy(audio), n_fft=2048, hop_length=480,
    window=torch.hann_window(2048), center=True, pad_mode="constant",
    return_complex=True,
).abs()
basis = torch.from_numpy(librosa.filters.mel(
    sr=48000, n_fft=2048, n_mels=128, htk=False, norm="slaney",
))
mel = torch.log(torch.clamp(basis @ spectrum, min=1e-5)).T[:(count + 479) // 480]
print(json.dumps({
    "sample_count": count,
    "frames": len(mel),
    "samples": [
        {"frame": frame, "mel": band, "value": float(mel[frame, band])}
        for frame in (0, 1, 4, 8) for band in (0, 12, 31, 64, 100, 127)
    ],
}, indent=2))
